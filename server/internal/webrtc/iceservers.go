package webrtc

import (
	"bytes"
	"crypto/hmac"
	"crypto/sha1"
	"encoding/base64"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"net/http"
	"net/url"
	"strconv"
	"time"

	"github.com/m1k1o/neko/server/pkg/types"
)

// how long generated TURN credentials stay valid when no TTL is configured
const defaultTURNCredentialTTL = 24 * time.Hour

// base URL of the Cloudflare Realtime TURN API, replaced in tests
var cloudflareTURNURL = "https://rtc.live.cloudflare.com/v1/turn/keys"

// the Cloudflare API is called while connecting, so do not wait too long for it
var cloudflareTURNClient = &http.Client{Timeout: 5 * time.Second}

// turnCredentials returns time-limited credentials for a TURN server using
// the TURN REST API (draft-uberti-behave-turn-rest), as implemented by
// coturn's use-auth-secret: the username is the expiry as a unix timestamp,
// followed by the user identifier, and the credential is the base64 encoded
// HMAC-SHA1 of the username keyed with the shared secret.
func turnCredentials(secret, user string, expires time.Time) (username, credential string) {
	username = strconv.FormatInt(expires.Unix(), 10)
	if user != "" {
		username += ":" + user
	}

	mac := hmac.New(sha1.New, []byte(secret))
	mac.Write([]byte(username))
	credential = base64.StdEncoding.EncodeToString(mac.Sum(nil))
	return
}

// cloudflareICEServers returns STUN and TURN servers of the Cloudflare
// Realtime TURN service, with new credentials generated using the TURN key
// and valid for the given duration.
func cloudflareICEServers(key *types.CloudflareTURN, ttl time.Duration) ([]types.ICEServer, error) {
	body, err := json.Marshal(map[string]int64{"ttl": int64(ttl / time.Second)})
	if err != nil {
		return nil, err
	}

	endpoint := cloudflareTURNURL + "/" + url.PathEscape(key.KeyID) + "/credentials/generate-ice-servers"
	req, err := http.NewRequest(http.MethodPost, endpoint, bytes.NewReader(body))
	if err != nil {
		return nil, err
	}
	req.Header.Set("Authorization", "Bearer "+key.APIToken)
	req.Header.Set("Content-Type", "application/json")
	req.Header.Set("Accept", "application/json")

	response, err := cloudflareTURNClient.Do(req)
	if err != nil {
		return nil, err
	}
	defer response.Body.Close()

	if response.StatusCode < 200 || response.StatusCode >= 300 {
		// the API explains what went wrong, e.g. {"error":"cannot find specified key"}
		message, _ := io.ReadAll(io.LimitReader(response.Body, 512))
		return nil, fmt.Errorf("cloudflare TURN API returned %s: %s", response.Status, bytes.TrimSpace(message))
	}

	var payload struct {
		ICEServers []types.ICEServer `json:"iceServers"`
	}
	if err := json.NewDecoder(io.LimitReader(response.Body, 1<<20)).Decode(&payload); err != nil {
		return nil, fmt.Errorf("cloudflare TURN API returned invalid response: %w", err)
	}

	if len(payload.ICEServers) == 0 {
		return nil, errors.New("cloudflare TURN API returned no ICE servers")
	}

	return payload.ICEServers, nil
}

// resolveICEServers returns the ICE servers to be used for a connection of
// the given user, replacing the credentials of servers that have a shared
// secret with ones generated for that user and valid from now on, and
// entries with a Cloudflare TURN key with the servers generated by
// Cloudflare. Entries that cannot be resolved are left out and their errors
// are returned along with the other servers.
func resolveICEServers(servers []types.ICEServer, user string, now time.Time) ([]types.ICEServer, error) {
	resolved := make([]types.ICEServer, 0, len(servers))

	var errs []error
	for _, server := range servers {
		ttl := time.Duration(server.TTL) * time.Second
		if ttl <= 0 {
			ttl = defaultTURNCredentialTTL
		}

		if server.Cloudflare != nil {
			generated, err := cloudflareICEServers(server.Cloudflare, ttl)
			if err != nil {
				errs = append(errs, fmt.Errorf("cloudflare TURN key %q: %w", server.Cloudflare.KeyID, err))
				continue
			}

			resolved = append(resolved, generated...)
			continue
		}

		if server.Secret != "" {
			server.Username, server.Credential = turnCredentials(server.Secret, user, now.Add(ttl))
			server.Secret = ""
			server.TTL = 0
		}

		resolved = append(resolved, server)
	}

	return resolved, errors.Join(errs...)
}
